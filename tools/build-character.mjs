// Turns a character exported from Figma (SVG with "Include id attribute" ON) into a JS module the app can draw.
// Usage:  node tools/build-character.mjs design/figma/estella-part-library.svg js/ui/characters/estella.js
//
// What it does:
//  - takes the assembled character ("Estella / Character / Starter")
//  - replaces its single face with the 4 aligned expressions (Amused, Focused, Excited, Blink) as class="expr expr-…"
//  - wraps the head (neck, hair, face, expressions) in class="m-head" so it can move a little when breathing
//  - turns the skin colors into CSS variables (--m-skin, --m-skin-shade) for skin tones later
//  - removes Figma's ids (several characters can be on one page without clashing)
// The expressions sit in a row in the part library, 180 px apart; EXPR_OFFSET moves each onto the face.
import fs from 'fs';

const [src, out] = process.argv.slice(2);
if (!src || !out) { console.error('usage: node tools/build-character.mjs <figma.svg> <out.js>'); process.exit(1); }
const svg = fs.readFileSync(src, 'utf8');

const CHARACTER = 'Estella / Character / Starter';
const FACE = 'Expression / face features';
const EXPRESSIONS = ['Amused', 'Focused', 'Excited', 'Blink'];
const EXPR_OFFSET = k => [212 - 180 * k, 595];          // part library position → face position
const BOX = { x: 123, y: 1851, w: 466, h: 1504 };         // whole character, with a little margin
const BUST = { x: 165, y: 1850, w: 350, h: 350 };         // head + shoulders (small spots)
const HEAD_FIRST = 'Neck_2', HEAD_LAST = 'Hair / front fringe_2';
const SKIN = { '#E9A36D': 'var(--m-skin,#E9A36D)', '#DE9966': 'var(--m-skin-shade,#DE9966)' };

// The full <g id="name">…</g> element.
function group(name, text = svg) {
  const start = text.indexOf(`<g id="${name}"`);
  if (start < 0) throw new Error(`layer not found: ${name}`);
  let depth = 0;
  const re = /<(\/?)g\b[^>]*?(\/?)>/g;
  re.lastIndex = start;
  for (let m; (m = re.exec(text));) {
    if (m[1]) depth--; else if (!m[2]) depth++;
    if (depth === 0) return text.slice(start, m.index + m[0].length);
  }
  throw new Error(`unclosed layer: ${name}`);
}

let body = group(CHARACTER);
const face = group(FACE, body);

// Head: everything from the neck to the front fringe (they are consecutive in the anatomy group).
const neck = group(HEAD_FIRST, body), fringe = group(HEAD_LAST, body);
const a = body.indexOf(neck), b = body.indexOf(fringe) + fringe.length;
body = `${body.slice(0, a)}<g class="m-head">${body.slice(a, b)}</g>${body.slice(b)}`;

const exprs = EXPRESSIONS.map((n, k) => {
  const [dx, dy] = EXPR_OFFSET(k);
  return group(`Expression=${n}`).replace(/^<g id="[^"]*"/, `<g class="expr expr-${n.toLowerCase()}" transform="translate(${dx} ${dy})"`);
}).join('');
body = body.replace(face, `<g class="m-head">${exprs}</g>`);

body = body.replace(/ id="[^"]*"/g, '');
for (const [hex, v] of Object.entries(SKIN)) body = body.split(`fill="${hex}"`).join(`style="fill:${v}"`);
body = body.replace(/\n\s*/g, '');

const js = `// Generated by tools/build-character.mjs from ${src.replace(/\\/g, '/')} — don't edit by hand.
export const VIEWBOX = ${JSON.stringify(BOX)};
export const BUST = ${JSON.stringify(BUST)};
export const BODY = ${JSON.stringify(body)};
`;
fs.writeFileSync(out, js);
console.log(`${out}: ${(js.length / 1024).toFixed(1)} KB`);
